#!/usr/bin/env bash
# Rebuild samples/release-<N>.txt from the genome files in data/release-<N>/genome/.
# A sample is the FungiDB organism abbreviation between "FungiDB-<N>_" and
# "_Genome.fasta[.gz]". Samples with no GFF or protein file are reported;
# scripts/02_fetch_fungidb_data.sh fetches those when FungiDB has them.
set -euo pipefail
source "${PROJECT_DIR:-$PWD}/config.sh"
mkdir -p "$(dirname "$SAMPLES_FILE")"
{
echo "# FungiDB release $FUNGIDB_RELEASE organism abbreviations, one per line, as used in"
echo "# https://fungidb.org/common/downloads/release-${FUNGIDB_RELEASE}/<ABBREV>/"
echo "# Generated by scripts/make_samples.sh from $DATA_DIR/genome/ on $(date +%Y-%m-%d)."
ls "$DATA_DIR/genome" | sed -n "s/^FungiDB-${FUNGIDB_RELEASE}_\(.*\)_Genome\.fasta\(\.gz\)\?$/\1/p" | sort -u
} > "$SAMPLES_FILE"
n=$(grep -cv '^#' "$SAMPLES_FILE")
echo "$SAMPLES_FILE: $n samples"
for s in $(grep -v '^#' "$SAMPLES_FILE"); do
    [ -e "$DATA_DIR/gff/FungiDB-${FUNGIDB_RELEASE}_${s}.gff.gz" ] || echo "  no GFF:     $s"
    [ -e "$DATA_DIR/protein/FungiDB-${FUNGIDB_RELEASE}_${s}_AnnotatedProteins.fasta.gz" ] || echo "  no protein: $s"
done
